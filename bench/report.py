#!/usr/bin/env python3
"""Regenerates the README benchmark section from bench/results/ (F032).

    .venv/bin/python bench/report.py

Reads every results JSON the harness has written, keeps the newest row per
(engine, precision, threads), and rewrites the block between the
BENCH:BEGIN / BENCH:END markers in README.md. Every number in that block
comes from a results file — nothing is typed by hand.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = ROOT / "bench" / "results"
README = ROOT / "README.md"
BEGIN = "<!-- BENCH:BEGIN (generated by bench/report.py — do not edit by hand) -->"
END = "<!-- BENCH:END -->"

# Rows print in this order; a missing config is simply left out.
# Key: (engine, precision, backend) — backend arrived with F033; rows from
# older results files default to "cpu".
ORDER = [
    ("nanoserve", "fp32", "cpu"),
    ("nanoserve", "fp32", "metal"),
    ("llama.cpp", "f32", "cpu"),
    ("nanoserve", "int8", "cpu"),
    ("nanoserve", "int8", "metal"),
    ("llama.cpp", "q8_0", "cpu"),
]


def load_latest() -> tuple[dict, dict, dict]:
    """Newest row per (engine, precision, backend); newest metadata."""
    latest: dict[tuple[str, str, str], dict] = {}
    stamps: dict[tuple[str, str, str], str] = {}
    meta: dict = {}
    meta_stamp = ""
    files = sorted(RESULTS_DIR.glob("results-*.json"))
    if not files:
        raise SystemExit("no results in bench/results/ — run bench/run.py first")
    for path in files:
        data = json.loads(path.read_text())
        stamp = data["created_utc"]
        if stamp > meta_stamp:
            meta_stamp = stamp
            meta = {"machine": data["machine"], "workload": data["workload"]}
        for row in data["rows"]:
            key = (row["engine"], row["precision"], row.get("backend", "cpu"))
            if key not in stamps or stamp > stamps[key]:
                stamps[key] = stamp
                latest[key] = row
    return latest, meta["machine"], meta["workload"]


def fmt(stat: dict, digits: int = 1) -> str:
    return f"{stat['mean']:.{digits}f} ± {stat['std']:.{digits}f}"


def gap_statement(latest: dict) -> list[str]:
    """The honest comparison, computed from the data (never hand-typed)."""
    lines = []
    for ours, theirs, label in [
        (("nanoserve", "fp32", "cpu"), ("llama.cpp", "f32", "cpu"), "fp32 vs f32"),
        (("nanoserve", "int8", "cpu"), ("llama.cpp", "q8_0", "cpu"), "int8 vs Q8_0"),
    ]:
        if ours in latest and theirs in latest:
            a = latest[ours]["decode_tps"]["mean"]
            b = latest[theirs]["decode_tps"]["mean"]
            if b > a:
                lines.append(
                    f"- **{label} decode:** llama.cpp is **{b / a:.2f}x faster** "
                    f"({b:.1f} vs {a:.1f} tok/s)."
                )
            else:
                lines.append(
                    f"- **{label} decode:** nanoserve is {a / b:.2f}x faster "
                    f"({a:.1f} vs {b:.1f} tok/s)."
                )
    # Metal vs our own CPU path (F033) — computed both ways, stated plainly
    # whichever direction it lands.
    for prec in ["fp32", "int8"]:
        gpu = ("nanoserve", prec, "metal")
        cpu = ("nanoserve", prec, "cpu")
        if gpu in latest and cpu in latest:
            for phase, name in [("decode_tps", "decode"), ("prefill_tps", "prefill")]:
                g = latest[gpu][phase]["mean"]
                c = latest[cpu][phase]["mean"]
                faster = "faster" if g > c else "slower"
                ratio = g / c if g > c else c / g
                if ratio < 1.05:
                    lines.append(
                        f"- **{prec} metal {name}:** at parity with our CPU "
                        f"path ({g:.1f} vs {c:.1f} tok/s)."
                    )
                else:
                    lines.append(
                        f"- **{prec} metal {name}:** {ratio:.2f}x {faster} than "
                        f"our CPU path ({g:.1f} vs {c:.1f} tok/s)."
                    )
    return lines


def render() -> str:
    latest, machine, workload = load_latest()

    lines = [BEGIN, ""]
    lines.append(
        f"Workload: {workload['prompt_tokens']}-token chat prompt "
        f"(\"{workload['prompt']}\"), {workload['gen_tokens']} greedy tokens, "
        f"{workload['warmup_runs']} warmup run."
    )
    lines.append(
        f"Hardware: {machine.get('chip', 'unknown')} "
        f"({machine.get('performance_cores', '?')}P + "
        f"{machine.get('efficiency_cores', '?')}E cores, "
        f"{machine.get('ram_gb', '?')} GB), macOS {machine.get('macos', '?')}."
    )
    lines.append("")
    lines.append("| engine | precision | backend | threads | prefill tok/s | decode tok/s | TTFT ms |")
    lines.append("|---|---|---|---:|---:|---:|---:|")
    for key in ORDER:
        if key not in latest:
            continue
        r = latest[key]
        engine = f"{r['engine']} (`{r['engine_version'].split('@')[1]}`)"
        lines.append(
            f"| {engine} | {r['precision']} | {r.get('backend', 'cpu')} "
            f"| {r['threads']} "
            f"| {fmt(r['prefill_tps'])} | {fmt(r['decode_tps'])} "
            f"| {r['ttft_ms']['mean']:.0f} |"
        )
    lines.append("")
    lines += gap_statement(latest)
    lines += [
        "",
        "Caveats, stated plainly: the f32 GGUF is converted from the exact "
        "safetensors file nanoserve loads, so the fp32 row is like-for-like; "
        "the int8 WEIGHT formats are NOT identical (nanoserve: per-row "
        "scales, 8.0 bits/weight; llama.cpp Q8_0: per-32-block scales, 8.5 "
        "bits/weight — finer-grained and slightly larger). On the CPU, both "
        "engines quantize activations to int8 per 32-value block at runtime "
        "and compute the dot products with integer SIMD (sdot). nanoserve numbers "
        "come from the engine's internal prefill/decode timers on a real "
        "prompt; llama.cpp numbers come from `llama-bench` with the same "
        "token counts, threads, and repeat count (its decode test starts "
        "from an empty context — at 0.5B the KV-read difference is ~3 "
        "MB/token vs ~0.5-2 GB/token of weights, i.e. under the noise "
        "floor). The thread count was chosen by measuring both engines at "
        "5 (performance cores) and 11 (all hardware threads): decode is "
        "fastest at 5 for BOTH engines on this chip (the sweep files sit in "
        "bench/results/). llama.cpp is its default macOS CPU build, which "
        "uses Accelerate BLAS for prompt processing — much of its prefill "
        "lead is Apple's GEMM, not ggml kernels.",
        "",
        "The metal rows (F033) offload ONLY the linear projections above a "
        "dispatch-amortization floor to the M-series GPU: attention, norms, "
        "RoPE, and the small per-token k/v projections stay on the CPU, and "
        "each GPU projection is one synchronous command-buffer round-trip "
        "(the CPU consumes every result immediately, so there is nothing to "
        "pipeline without restructuring the engine). Decode therefore pays "
        "that round-trip ~121 times per token, which is the number to watch "
        "in the decode column. Weights are GPU-resident zero-copy (unified "
        "memory; registered once at load). The GPU int8 kernel dequantizes "
        "weights in-register against fp32 activations — no activation "
        "quantization, unlike the CPU sdot path, so it is slightly MORE "
        "accurate (bit-identical to the fp32 goldens on all 4 greedy "
        "prompts, where the CPU int8 path has one documented near-tie "
        "flip). llama.cpp stays CPU-only in this table.",
        "",
        "Reproduce:",
        "",
        "```sh",
        "bash bench/setup_llamacpp.sh   # clone+build llama.cpp (pinned), convert GGUFs",
        ".venv/bin/python bench/run.py --engine all --repeats 5",
        ".venv/bin/python bench/report.py",
        "```",
        "",
        END,
    ]
    return "\n".join(lines)


def main() -> None:
    text = README.read_text()
    begin = text.find(BEGIN)
    end = text.find(END)
    if begin == -1 or end == -1:
        raise SystemExit("README.md is missing the BENCH:BEGIN/END markers")
    updated = text[:begin] + render() + text[end + len(END):]
    README.write_text(updated)
    print(f"updated {README.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
