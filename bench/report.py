#!/usr/bin/env python3
"""Regenerates the README benchmark section from bench/results/ (F032).

    .venv/bin/python bench/report.py

Reads every results JSON the harness has written, keeps the newest row per
(engine, precision, threads), and rewrites the block between the
BENCH:BEGIN / BENCH:END markers in README.md. Every number in that block
comes from a results file — nothing is typed by hand.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = ROOT / "bench" / "results"
README = ROOT / "README.md"
BEGIN = "<!-- BENCH:BEGIN (generated by bench/report.py — do not edit by hand) -->"
END = "<!-- BENCH:END -->"

# Rows print in this order; a missing config is simply left out.
ORDER = [
    ("nanoserve", "fp32"),
    ("llama.cpp", "f32"),
    ("nanoserve", "int8"),
    ("llama.cpp", "q8_0"),
]


def load_latest() -> tuple[dict, dict, dict]:
    """Newest row per (engine, precision); newest machine/workload metadata."""
    latest: dict[tuple[str, str], dict] = {}
    stamps: dict[tuple[str, str], str] = {}
    meta: dict = {}
    meta_stamp = ""
    files = sorted(RESULTS_DIR.glob("results-*.json"))
    if not files:
        raise SystemExit("no results in bench/results/ — run bench/run.py first")
    for path in files:
        data = json.loads(path.read_text())
        stamp = data["created_utc"]
        if stamp > meta_stamp:
            meta_stamp = stamp
            meta = {"machine": data["machine"], "workload": data["workload"]}
        for row in data["rows"]:
            key = (row["engine"], row["precision"])
            if key not in stamps or stamp > stamps[key]:
                stamps[key] = stamp
                latest[key] = row
    return latest, meta["machine"], meta["workload"]


def fmt(stat: dict, digits: int = 1) -> str:
    return f"{stat['mean']:.{digits}f} ± {stat['std']:.{digits}f}"


def gap_statement(latest: dict) -> list[str]:
    """The honest comparison, computed from the data (never hand-typed)."""
    lines = []
    for ours, theirs, label in [
        (("nanoserve", "fp32"), ("llama.cpp", "f32"), "fp32 vs f32"),
        (("nanoserve", "int8"), ("llama.cpp", "q8_0"), "int8 vs Q8_0"),
    ]:
        if ours in latest and theirs in latest:
            a = latest[ours]["decode_tps"]["mean"]
            b = latest[theirs]["decode_tps"]["mean"]
            if b > a:
                lines.append(
                    f"- **{label} decode:** llama.cpp is **{b / a:.2f}x faster** "
                    f"({b:.1f} vs {a:.1f} tok/s)."
                )
            else:
                lines.append(
                    f"- **{label} decode:** nanoserve is {a / b:.2f}x faster "
                    f"({a:.1f} vs {b:.1f} tok/s)."
                )
    return lines


def render() -> str:
    latest, machine, workload = load_latest()

    lines = [BEGIN, ""]
    lines.append(
        f"Workload: {workload['prompt_tokens']}-token chat prompt "
        f"(\"{workload['prompt']}\"), {workload['gen_tokens']} greedy tokens, "
        f"{workload['warmup_runs']} warmup run, CPU only."
    )
    lines.append(
        f"Hardware: {machine.get('chip', 'unknown')} "
        f"({machine.get('performance_cores', '?')}P + "
        f"{machine.get('efficiency_cores', '?')}E cores, "
        f"{machine.get('ram_gb', '?')} GB), macOS {machine.get('macos', '?')}."
    )
    lines.append("")
    lines.append("| engine | precision | threads | prefill tok/s | decode tok/s | TTFT ms |")
    lines.append("|---|---|---:|---:|---:|---:|")
    for key in ORDER:
        if key not in latest:
            continue
        r = latest[key]
        engine = f"{r['engine']} (`{r['engine_version'].split('@')[1]}`)"
        lines.append(
            f"| {engine} | {r['precision']} | {r['threads']} "
            f"| {fmt(r['prefill_tps'])} | {fmt(r['decode_tps'])} "
            f"| {r['ttft_ms']['mean']:.0f} |"
        )
    lines.append("")
    lines += gap_statement(latest)
    lines += [
        "",
        "Caveats, stated plainly: the f32 GGUF is converted from the exact "
        "safetensors file nanoserve loads, so the fp32 row is like-for-like; "
        "the int8 formats are NOT identical (nanoserve: per-row scales, "
        "8.0 bits/weight; llama.cpp Q8_0: per-32-block scales, 8.5 "
        "bits/weight — finer-grained and slightly larger). nanoserve numbers "
        "come from the engine's internal prefill/decode timers on a real "
        "prompt; llama.cpp numbers come from `llama-bench` with the same "
        "token counts, threads, and repeat count (its decode test starts "
        "from an empty context — at 0.5B the KV-read difference is ~3 "
        "MB/token vs ~0.5-2 GB/token of weights, i.e. under the noise "
        "floor). The thread count was chosen by measuring both engines at "
        "5 (performance cores) and 11 (all hardware threads): decode is "
        "fastest at 5 for BOTH engines on this chip (the sweep files sit in "
        "bench/results/). llama.cpp is its default macOS CPU build, which "
        "uses Accelerate BLAS for prompt processing — much of its prefill "
        "lead is Apple's GEMM, not ggml kernels.",
        "",
        "Reproduce:",
        "",
        "```sh",
        "bash bench/setup_llamacpp.sh   # clone+build llama.cpp (pinned), convert GGUFs",
        ".venv/bin/python bench/run.py --engine all --repeats 5",
        ".venv/bin/python bench/report.py",
        "```",
        "",
        END,
    ]
    return "\n".join(lines)


def main() -> None:
    text = README.read_text()
    begin = text.find(BEGIN)
    end = text.find(END)
    if begin == -1 or end == -1:
        raise SystemExit("README.md is missing the BENCH:BEGIN/END markers")
    updated = text[:begin] + render() + text[end + len(END):]
    README.write_text(updated)
    print(f"updated {README.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
